import Foundation

/// Represents a file or folder entry inside File Station.
public struct DsmFile: Codable, Sendable, Identifiable, Hashable {
    public var id: String { path }
    public var path: String
    public var name: String
    public var isdir: Bool
    public var size: Int64
    public var mtime: Int64
    public var owner: String?
    public var filetype: String?
    public var perm: String?
    public var realPath: String?
    public var itemCount: Int?
    public var mimeType: String?

    public init(
        path: String,
        name: String,
        isdir: Bool,
        size: Int64 = 0,
        mtime: Int64 = 0,
        owner: String? = nil,
        filetype: String? = nil,
        perm: String? = nil,
        realPath: String? = nil,
        itemCount: Int? = nil,
        mimeType: String? = nil
    ) {
        self.path = path
        self.name = name
        self.isdir = isdir
        self.size = size
        self.mtime = mtime
        self.owner = owner
        self.filetype = filetype
        self.perm = perm
        self.realPath = realPath
        self.itemCount = itemCount
        self.mimeType = mimeType
    }

    /// File extension in lowercase, empty for directories.
    public var fileExtension: String {
        guard !isdir else { return "" }
        guard let dotIndex = name.lastIndex(of: ".") else { return "" }
        return String(name[name.index(after: dotIndex)...]).lowercased()
    }

    public var isMedia: Bool {
        isVideo || isAudio || isImage
    }

    public var isVideo: Bool {
        let videoExts: Set<String> = ["mp4", "mkv", "avi", "mov", "webm", "3gp", "ts", "m4v", "flv", "wmv"]
        return videoExts.contains(fileExtension)
    }

    public var isAudio: Bool {
        let audioExts: Set<String> = ["mp3", "flac", "wav", "m4a", "aac", "ogg", "wma", "opus", "mka"]
        return audioExts.contains(fileExtension)
    }

    public var isImage: Bool {
        let imageExts: Set<String> = ["jpg", "jpeg", "png", "webp", "gif", "svg", "bmp", "ico", "heic", "heif"]
        return imageExts.contains(fileExtension)
    }

    public var isText: Bool {
        let textExts: Set<String> = ["txt", "log", "json", "yml", "yaml", "xml", "conf", "sh", "js", "ts", "md", "swift", "kt", "py"]
        return textExts.contains(fileExtension)
    }
}

/// Backward compatibility alias matching Kotlin codebase.
public typealias FileItem = DsmFile

/// File sharing link generated by File Station.
public struct FileShareLink: Codable, Sendable, Identifiable, Hashable {
    public var id: String
    public var url: String
    public var path: String
    public var name: String
    public var dateExpired: String?
    public var hasPassword: Bool

    public init(
        id: String,
        url: String,
        path: String,
        name: String,
        dateExpired: String? = nil,
        hasPassword: Bool = false
    ) {
        self.id = id
        self.url = url
        self.path = path
        self.name = name
        self.dateExpired = dateExpired
        self.hasPassword = hasPassword
    }
}

/// Backward compatibility alias matching Kotlin codebase.
public typealias ShareLink = FileShareLink

/// Information about a mounted storage volume in File Station context.
public struct StorageVolumeInfo: Codable, Sendable, Identifiable, Hashable {
    public var id: String { volumePath }
    public var volumePath: String
    public var description: String
    public var freeSpaceBytes: Int64
    public var totalSpaceBytes: Int64

    public init(
        volumePath: String,
        description: String = "",
        freeSpaceBytes: Int64 = 0,
        totalSpaceBytes: Int64 = 0
    ) {
        self.volumePath = volumePath
        self.description = description
        self.freeSpaceBytes = freeSpaceBytes
        self.totalSpaceBytes = totalSpaceBytes
    }

    public var usedSpaceBytes: Int64 {
        max(0, totalSpaceBytes - freeSpaceBytes)
    }

    public var usedPercent: Double {
        guard totalSpaceBytes > 0 else { return 0.0 }
        return (Double(usedSpaceBytes) / Double(totalSpaceBytes)) * 100.0
    }
}
